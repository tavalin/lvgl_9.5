# * Page-0 R80h = 0x01 selects 2 lanes (vendor file had 0x03 = 4 lanes).
# * SLPOUT is sent here with a 120 ms settle (no_slpout suppresses the generic 10 ms one).
# * The short porches leave no LP command gaps once video runs, so the whole init
#   sequence is sent before DPI video starts (init_before_video).
# * STBYB must be high before reset: wire it as enable_pin.
